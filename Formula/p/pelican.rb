  deny_network_access!

  def fetch
    resource("watchfiles").stage do
      system "cargo", "fetch", *std_cargo_fetch_args
      system "cargo", "metadata", "--locked", "--format-version=1"
    end

    resource("maturin").stage do
      system "cargo", "fetch", *std_cargo_fetch_args
      system "cargo", "metadata", "--locked", "--format-version=1"
    end
  end

  def install
    ENV["PIP_NO_INDEX"] = "1"
    ENV["PIP_NO_CACHE_DIR"] = "1"
    venv = virtualenv_create(libexec, "python3.14", system_site_packages: false)
    ENV.append_path "PATH", venv.root/"bin"
    bootstrap = %w[
      setuptools
      flit-core
      poetry-core
      pdm-backend
      markdown
      markupsafe
      six
      unidecode
      calver
      semantic-version
      blinker
      docutils
      idna
      mdurl
      ordered-set
      typing-extensions
      packaging
      pathspec
      tomlkit
      jinja2
      trove-classifiers
      markdown-it-py
      setuptools-scm
      wheel
      anyio
      pluggy
      setuptools-rust
      python-dateutil
      hatchling
      maturin
      feedgenerator
      pygments
      watchfiles
      rich
    ]
    bootstrap.each do |name|
      venv.pip_install resource(name), build_isolation: false
    end
    venv.pip_install_and_link buildpath, build_isolation: false
    # Remove ARM binaries on Intel macOS
    rm_r libexec.glob("lib/python*.*/site-packages/pelican/build/aarch64-*") if OS.mac? && Hardware::CPU.intel?
  end

